int main(int argc, char *argv[])
{
  const int N = 1e7 + 3;
  static bool prime[N];
  fill(prime, prime + N, true);
  prime[0] = prime[1] = false;
  for (long long int i = 2; i * i < N; ++i) {
    for (long long int j = 2; i * j < N; ++j) {
      prime[i * j] = false;
    }
  }
  vector<long long int> ps;
  for (int i = 0; i < N; ++i) {
    if (prime[i]) ps.push_back(i);
  }
  vec<str> v;
  each (i, ps) {
    v.push_back(to_string(i));
  }

  str s;
  while (cin >> s) {
    str u = "-1";
    each (t, v) {
      if (s.size() == t.size()) {
        map<char, char> m1;
        for (int i = 0; i < s.size(); ++i) {
          m1[s[i]] = t[i];
        }
        map<char, char> m2;
        for (int i = 0; i < t.size(); ++i) {
          m2[t[i]] = s[i];
        }
        bool f = true;
        for (int i = 0; i < s.size(); ++i) {
          f = f && (m1[s[i]] == t[i]);
          f = f && (m2[t[i]] == s[i]);
        }
        if (f) {
          u = t;
          break;
        }
      }
    }
    cout << u << endl;
  }
  return 0;
}
